"""Stage curated guides for Fern; repository Markdown remains authoritative."""

import json
import re
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit

ROOT = Path(__file__).resolve().parents[2]
PAGES = json.loads((ROOT / "scripts/docs/pages.json").read_text())
SLUGS = {(ROOT / page["source"]).resolve(): page["slug"] for page in PAGES}


def link_for_site(match: re.Match[str], source: Path) -> str:
    """Route curated links locally and other existing repository files to GitHub."""
    label, url = match.groups()
    parsed = urlsplit(url)
    if parsed.scheme or url.startswith(("#", "/")):
        return match.group(0)
    target = (source.parent / unquote(parsed.path)).resolve()
    if not target.exists():
        raise ValueError(f"{source.relative_to(ROOT)}: missing link target {url}")
    relative = target.relative_to(ROOT)
    if target in SLUGS:
        result = "/" + SLUGS[target]
    else:
        kind = "tree" if target.is_dir() else "blob"
        result = f"https://github.com/dsx-ai-factory/NVIDIA-Recovery/{kind}/main/{quote(str(relative))}"
    if parsed.fragment:
        result += "#" + parsed.fragment
    return f"[{label}]({result})"


def main() -> None:
    """Generate only the allowlisted pages, without rewriting fenced examples."""
    output = ROOT / "fern/generated"
    output.mkdir(exist_ok=True)
    for page in PAGES:
        source = ROOT / page["source"]
        lines = []
        fence = None
        for line in source.read_text().splitlines(keepends=True):
            delimiter = re.match(r"^\s*(`{3,}|~{3,})", line)
            if delimiter:
                token = delimiter.group(1)
                if fence is None:
                    fence = token
                elif token[0] == fence[0] and len(token) >= len(fence):
                    fence = None
            elif fence is None:
                line = re.sub(r"\[([^\]\n]+)\]\(([^\s)]+)\)", lambda m, source=source: link_for_site(m, source), line)
            lines.append(line)
        header = "{/* Generated by scripts/docs/prepare.py; edit " + page["source"] + ". */}\n\n"
        (output / (page["slug"] + ".mdx")).write_text(header + "".join(lines))
    print(f"Prepared {len(PAGES)} curated Fern pages")


if __name__ == "__main__":
    main()
