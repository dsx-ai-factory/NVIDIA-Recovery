"""Golden test for the attribution_adapter FACT v2 migration (design §11).

For every fixture case in ``golden_fixtures`` this test drives the FULL pipeline:

  FACT ``AttributionResponseV2``
    -> ``attribution_adapter.response_builder.build_response``  (NV side)
    -> ``anomaly_detection_isolator.result_builder.build_attribution_result``  (Policy side)
    -> ``AnomalyProcessor._sanitize_attribution_result``  (Policy side)

and asserts the resulting ``AnomalyAttributionResult.to_json()`` is structurally
IDENTICAL to the frozen v2 golden snapshot in ``golden_messages.json``.

``golden_messages.json`` is regenerated by this pipeline over the v2 fixtures during
the Task 4 migration.  After regeneration it is FROZEN as a regression oracle: a
divergence is a real pipeline bug, not a test-maintenance issue.
"""

import json
from pathlib import Path

import golden_fixtures
import pytest
from anomaly_detection_isolator.anomaly_processor import AnomalyProcessor
from anomaly_detection_isolator.result_builder import build_attribution_result
from recovery_libs.storage.node_events import ErrorAttributionType

from attribution_adapter import response_builder

GOLDEN_PATH = Path(__file__).parent / "golden_messages.json"
GOLDEN_MESSAGES = json.loads(GOLDEN_PATH.read_text())

# The fixed capture config used to freeze the golden snapshot.
_CAPTURE = golden_fixtures.capture_settings()


def _sanitize(result, job_status):
    """Apply ``_sanitize_attribution_result`` with the fixed capture settings.

    Construct an AnomalyProcessor without running its real __init__ (which would need a
    full Settings env) and pin the fixed capture settings, then invoke
    the real sanitize method.
    """
    proc = AnomalyProcessor.__new__(AnomalyProcessor)
    proc.settings = golden_fixtures.capture_settings()
    return proc._sanitize_attribution_result(result, job_status)


@pytest.mark.parametrize("case", golden_fixtures.CASE_NAMES)
def test_golden_byte_identity(case):
    """The v2 pipeline reproduces the frozen golden bytes for every fixture case."""
    fact_response = golden_fixtures.build_cases()[case]
    job_status = golden_fixtures.make_job_status()

    request = golden_fixtures.make_request()

    resp = response_builder.build_response(fact_response, request, attribution_session_id="sess")

    result = build_attribution_result(
        resp,
        job_status,
        golden_fixtures.ANOMALY_TYPE,
        golden_fixtures.ANOMALY_UUID,
        ErrorAttributionType.FAST,
        _CAPTURE,
    )

    result = _sanitize(result, job_status)

    actual = json.loads(result.to_json())
    expected = GOLDEN_MESSAGES[case]

    assert actual == expected, (
        f"Golden byte-identity MISMATCH for case '{case}'.\n"
        f"--- expected (frozen v2 golden) ---\n{json.dumps(expected, indent=2, sort_keys=True)}\n"
        f"--- actual (new pipeline) ---\n{json.dumps(actual, indent=2, sort_keys=True)}"
    )


def test_all_eight_cases_present():
    """Guard: the golden snapshot covers all eight fixture cases (none silently dropped)."""
    assert len(golden_fixtures.CASE_NAMES) == 8
    assert set(GOLDEN_MESSAGES.keys()) == set(golden_fixtures.CASE_NAMES)
