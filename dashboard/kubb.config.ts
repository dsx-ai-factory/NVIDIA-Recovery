import { adapterOas } from "@kubb/adapter-oas";
import { pluginAxios } from "@kubb/plugin-axios";
import { pluginTs, resolverTs } from "@kubb/plugin-ts";
import { pluginZod, resolverZod } from "@kubb/plugin-zod";
import { defineConfig } from "kubb/config";

const GENERATED_BANNER = "// @generated by Kubb. DO NOT EDIT.";
const GENERATED_MARKER_HOOK = "node scripts/mark-generated.mjs";

const UNICODE_SCALAR_LIMIT = `.refine((value) => { const characters = Array.from(value); return characters.length <= 256 && characters.every((character) => character.length !== 1 || character.charCodeAt(0) < 0xd800 || character.charCodeAt(0) > 0xdfff); }, { message: "Must contain at most 256 Unicode scalar values" })`;

// grpc-gateway does not carry field-level OpenAPI length constraints onto
// URL-bound parameters. These source descriptions identify the canonical
// workflow ID parameters on the primary and compatibility routes.
const CANONICAL_WORKFLOW_ID_PARAMETER_DESCRIPTIONS = new Set([
  "The opaque identifier of the workflow to get.",
  "The opaque identifier of the workflow assigned by NVIDIA Recovery.",
]);

