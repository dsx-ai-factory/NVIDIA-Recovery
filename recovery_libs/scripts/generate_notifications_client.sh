ROOT_FOLDER=$(git rev-parse --show-toplevel)

docker run --rm \
    -v ${ROOT_FOLDER}:/local \
    'openapitools/openapi-generator-cli:v7.12.0' \
    generate \
    -i /local/notifications/openapi.yaml \
    -g python \
    --additional-properties=generateSourceCodeOnly=true,packageName=recovery_libs.notifications_client,projectName=notifications_client \
    -o /local/recovery_libs

# OpenAPI Generator owns the surrounding docstring. Make its generated-file
# marker unambiguous so policy scanners do not mistake the output for authored
# source. The backup suffix keeps this command portable across BSD and GNU sed.
find "${ROOT_FOLDER}/recovery_libs/recovery_libs/notifications_client" -type f -name '*.py' \
    -exec sed -i.bak \
    's|Generated by OpenAPI Generator (https://openapi-generator.tech)|@generated by OpenAPI Generator (https://openapi-generator.tech). DO NOT EDIT.|g' {} +
find "${ROOT_FOLDER}/recovery_libs/recovery_libs/notifications_client" -type f -name '*.bak' -delete

# A few supporting templates omit the standard generator docstring. Add the
# same marker to those files without duplicating it on repeat generations.
find "${ROOT_FOLDER}/recovery_libs/recovery_libs/notifications_client" -type f -name '*.py' \
    -exec sh -c '
        for file do
            if ! grep -q "@generated" "${file}"; then
                temporary_file="${file}.generated-marker"
                awk '\''BEGIN { print "# @generated by OpenAPI Generator. DO NOT EDIT." } NR == 1 { print "" } { print }'\'' \
                    "${file}" >"${temporary_file}"
                mv "${temporary_file}" "${file}"
            fi
        done
    ' sh {} +
